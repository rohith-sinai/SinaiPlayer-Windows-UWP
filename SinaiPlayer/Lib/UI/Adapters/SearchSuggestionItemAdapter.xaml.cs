namespace SinaiPlayer.Lib.UI.Adapters
{
    public sealed partial class SearchSuggestionItemAdapter : UserControl
    {
        public SearchSuggestionItemAdapter()
        {
            InitializeComponent();
            this.DataContextChanged += Adapter_DataContextChanged;
        }

        private async void Adapter_DataContextChanged(FrameworkElement sender, DataContextChangedEventArgs args)
        {
            Bindings.Update();

            if (DataContext is SearchSuggestionViewModel vm)
            {
                await vm.LoadArtworkAsync();
            }
        }
    }
}
